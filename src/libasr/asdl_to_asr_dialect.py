GENERATED_FILE_BANNER = "// Generated by asdl_to_asr_dialect.py — do not edit."


def generated_file_lines(*lines: str) -> list[str]:
    """Prefix fully generated file contents with the standard banner."""
    return [GENERATED_FILE_BANNER, ""] + list(lines)


def snake_case(name: str) -> str:
    out = []
    for i, ch in enumerate(name):
        if ch.isupper() and i > 0:
            out.append("_")
        out.append(ch.lower())
    return "".join(out)


def enum_kind(category: str, name: str) -> str:
    return f"ASR_DIALECT_OP_{category.upper()}_{name.upper()}"


def mlir_op_name(name: str) -> str:
    return f"asr.{snake_case(name)}"

def c_param_name(name: str) -> str:
    if name in CPP_KEYWORDS:
        return name + "_"
    return name

# Map ASDL field types to MLIR field kinds, in C++ Codes.
def field_kind(asdl_type: str, seq: bool, opt: bool) -> str:
    if asdl_type in SIMPLE_SUM_NAMES:
        base = "I64"
    elif asdl_type == "symbol":
        base = "SYMBOL_REF"
    elif asdl_type in ("expr", "stmt", "ttype", "node"):
        base = asdl_type.upper()
    elif asdl_type == "identifier":
        base = "IDENTIFIER"
    elif asdl_type == "string":
        base = "STRING"
    elif asdl_type == "int":
        base = "I64"
    elif asdl_type == "bool":
        base = "BOOL"
    elif asdl_type == "float":
        base = "F64"
    elif asdl_type == "void":
        base = "VOID"
    elif asdl_type.endswith("Type"):
        base = "I64"
    else:
        base = "OP"
    if seq:
        return f"ASR_FIELD_{base}_SEQ"
    if opt:
        return f"ASR_FIELD_{base}_OPT"
    return f"ASR_FIELD_{base}"

OP_HANDLE_SEQ_FIELD_KINDS = {
    "ASR_FIELD_OP_SEQ",
    "ASR_FIELD_NODE_SEQ",
    "ASR_FIELD_EXPR_SEQ",
    "ASR_FIELD_STMT_SEQ",
    "ASR_FIELD_SYMBOL_SEQ",
}


# Assign a ASR Value inside a Node to ASR Dialect Field structure.
def gen_field_assign(i: int, f: asdl.Field, param: str) -> list[str]:
    fname = f.name or f.type
    fk = field_kind(f.type, f.seq, f.opt)
    lines = [
        f"    fields[{i}].kind = {fk};",
        f"    fields[{i}].name = \"{fname}\";",
    ]
    if f.type in ("identifier", "string", "symbol"):
        lines.append(f"    fields[{i}].value.str = {param};")
    elif f.type == "bool":
        lines.append(f"    fields[{i}].value.b = {param};")
    elif f.type == "float":
        lines.append(f"    fields[{i}].value.f64 = {param};")
    elif f.type == "int" or is_enum_field(f.type) or f.type == "void":
        lines.append(f"    fields[{i}].value.i64 = {param};")
    elif f.type == "ttype":
        lines.append(f"    fields[{i}].value.type = {param};")
    elif f.seq and fk in OP_HANDLE_SEQ_FIELD_KINDS:
        lines.append(f"    fields[{i}].value.op_seq.items = {param};")
        lines.append(f"    fields[{i}].value.op_seq.n_items = n_{param};")
    else:
        lines.append(f"    fields[{i}].value.op = {param};")
    return lines


# Create a list of operations from the ASDL module.
def stored_dialect_fields(op: dict) -> list:
    """Fields stored on ASR dialect ops (may differ from ASR.asdl for mlir-new)."""
    if op["name"] == "ArrayConstant":
        # Do not store raw ASR heap pointers in dialect IR; use element expr ops.
        return [
            asdl.Field("expr", "elements", seq=True),
            asdl.Field("ttype", "type"),
            asdl.Field("arraystorage", "storage_format"),
        ]
    return [f for f in op["fields"] if f.name not in SKIP_FIELDS]


def collect_ops(mod: asdl.Module) -> list[dict]:
    ops = []
    # Ignore simple no-operation enum types, like intent.
    for dfn in mod.dfns:
        cat = dfn.name
        val = dfn.value
        if isinstance(val, asdl.Product):
            ops.append({
                "category": cat,
                "name": cat,
                "fields": val.fields,
                "kind": enum_kind(cat, cat),
                "mlir_name": mlir_op_name(cat),
            })
        elif cat in OP_CATEGORIES or cat in PRODUCT_OP_CATEGORIES:
            for cons in val.types:
                ops.append({
                    "category": cat,
                    "name": cons.name,
                    "fields": cons.fields,
                    "kind": enum_kind(cat, cons.name),
                    "mlir_name": mlir_op_name(cons.name),
                })
    ops.sort(key=lambda o: (o["category"], o["name"]))
    return ops


def collect_simple_enums(mod: asdl.Module) -> dict[str, list[str]]:
    enums = {}
    for dfn in mod.dfns:
        # Collect simple enum types, like binop, intent etc, which dont have
        # an ASR Dialect operation (example: intent).
        if dfn.name in SIMPLE_SUM_NAMES and isinstance(dfn.value, asdl.Sum):
            enums[dfn.name] = [c.name for c in dfn.value.types]
    return enums


def gen_schema_h(ops: list[dict]) -> str:
    cat_map = {
        "unit": "ASR_DIALECT_CATEGORY_UNIT",
        "symbol": "ASR_DIALECT_CATEGORY_SYMBOL",
        "stmt": "ASR_DIALECT_CATEGORY_STMT",
        "expr": "ASR_DIALECT_CATEGORY_EXPR",
        "ttype": "ASR_DIALECT_CATEGORY_TTYPE",
    }
    lines = generated_file_lines(
        "#pragma once",
        "",
        "#include <stddef.h>",
        "",
        "typedef enum {",
        "    ASR_DIALECT_OP_INVALID = 0,",
    )
    for op in ops:
        lines.append(f"    {op['kind']},")
    lines.extend([
        "    ASR_DIALECT_OP_COUNT",
        "} ASR_DialectOpKind;",
        "",
        "typedef enum {",
        "    ASR_DIALECT_CATEGORY_UNIT,",
        "    ASR_DIALECT_CATEGORY_SYMBOL,",
        "    ASR_DIALECT_CATEGORY_STMT,",
        "    ASR_DIALECT_CATEGORY_EXPR,",
        "    ASR_DIALECT_CATEGORY_TTYPE,",
        "    ASR_DIALECT_CATEGORY_PRODUCT,",
        "} ASR_DialectCategory;",
        "",
        "typedef enum {",
        "    ASR_FIELD_I64, ASR_FIELD_F64, ASR_FIELD_BOOL,",
        "    ASR_FIELD_STRING, ASR_FIELD_IDENTIFIER,",
        "    ASR_FIELD_SYMBOL_REF, ASR_FIELD_SYMBOL_REF_OPT, ASR_FIELD_SYMBOL_REF_SEQ,",
        "    ASR_FIELD_EXPR, ASR_FIELD_STMT, ASR_FIELD_SYMBOL,",
        "    ASR_FIELD_TTYPE, ASR_FIELD_NODE, ASR_FIELD_OP,",
        "    ASR_FIELD_VOID, ASR_FIELD_I64_SEQ, ASR_FIELD_F64_SEQ,",
        "    ASR_FIELD_BOOL_SEQ, ASR_FIELD_STRING_SEQ,",
        "    ASR_FIELD_IDENTIFIER_SEQ, ASR_FIELD_EXPR_SEQ,",
        "    ASR_FIELD_STMT_SEQ, ASR_FIELD_SYMBOL_SEQ,",
        "    ASR_FIELD_TTYPE_SEQ, ASR_FIELD_NODE_SEQ, ASR_FIELD_OP_SEQ,",
        "    ASR_FIELD_EXPR_OPT, ASR_FIELD_STMT_OPT, ASR_FIELD_SYMBOL_OPT,",
        "    ASR_FIELD_TTYPE_OPT, ASR_FIELD_NODE_OPT, ASR_FIELD_I64_OPT,",
        "    ASR_FIELD_F64_OPT, ASR_FIELD_STRING_OPT,",
        "    ASR_FIELD_IDENTIFIER_OPT, ASR_FIELD_BOOL_OPT,",
        "} ASR_DialectFieldKind;",
        "",
        "typedef enum { ASR_FIELD_REQUIRED, ASR_FIELD_OPTIONAL } ASR_FieldPresence;",
        "",
        "typedef struct {",
        "    const char *name;",
        "    ASR_DialectFieldKind kind;",
        "    ASR_FieldPresence presence;",
        "} ASR_DialectFieldDesc;",
        "",
        "typedef struct {",
        "    ASR_DialectOpKind kind;",
        "    ASR_DialectCategory category;",
        "    const char *asr_name;",
        "    const char *mlir_name;",
        "    size_t n_fields;",
        "    const ASR_DialectFieldDesc *fields;",
        "} ASR_DialectOpSchema;",
        "",
    ])
    for op in ops:
        stored = stored_dialect_fields(op)
        if not stored:
            continue
        lines.append(f"static const ASR_DialectFieldDesc {op['kind']}_FIELDS[] = {{")
        for f in stored:
            fk = field_kind(f.type, f.seq, f.opt)
            pres = "ASR_FIELD_OPTIONAL" if f.opt else "ASR_FIELD_REQUIRED"
            fname = f.name or f.type
            lines.append(f'    {{"{fname}", {fk}, {pres}}},')
        lines.append("};")
        lines.append("")

    lines.append("static const ASR_DialectOpSchema ASR_DIALECT_SCHEMA[] = {")
    for op in ops:
        stored = stored_dialect_fields(op)
        cat = cat_map.get(op["category"], "ASR_DIALECT_CATEGORY_PRODUCT")
        fields_ref = f"{op['kind']}_FIELDS" if stored else "NULL"
        lines.append("    {")
        lines.append(f"        .kind = {op['kind']},")
        lines.append(f"        .category = {cat},")
        lines.append(f'        .asr_name = "{op["name"]}",')
        lines.append(f'        .mlir_name = "{op["mlir_name"]}",')
        lines.append(f"        .n_fields = {len(stored)},")
        lines.append(f"        .fields = {fields_ref},")
        lines.append("    },")
    lines.extend([
        "};",
        "",
        "static const size_t ASR_DIALECT_SCHEMA_COUNT =",
        "    sizeof(ASR_DIALECT_SCHEMA) / sizeof(ASR_DIALECT_SCHEMA[0]);",
        "",
    ])
    return "\n".join(lines)


def gen_api_generated_h(ops: list[dict]) -> str:
    lines = generated_file_lines(
        "// Include from C/C++ translation units only (not from asr_dialect_api.h).",
        "#pragma once",
        "",
        "#include \"asr_dialect_api.h\"",
        "",
    )
    for op in ops:
        stored = stored_dialect_fields(op)
        params = ["MLIR_Context *ctx", "MLIR_LocationHandle loc"]
        for f in stored:
            fname = c_param_name(f.name or f.type)
            if f.seq and f.type in ("expr", "stmt", "node"):
                params.append(f"MLIR_OpHandle *{fname}")
                params.append(f"size_t n_{fname}")
            elif f.type in ("expr", "stmt", "node"):
                params.append(f"MLIR_OpHandle {fname}")
            elif f.type == "symbol":
                params.append(f"ASR_SymbolRef {fname}")
            elif f.type == "ttype":
                params.append(f"MLIR_TypeHandle {fname}")
            elif f.type in ("identifier", "string"):
                params.append(f"string {fname}")
            elif f.type == "int" or is_enum_field(f.type):
                params.append(f"int64_t {fname}")
            elif f.type == "bool":
                params.append(f"bool {fname}")
            elif f.type == "float":
                params.append(f"double {fname}")
            elif f.seq:
                params.append(f"MLIR_OpHandle *{fname}")
                params.append(f"size_t n_{fname}")
            else:
                params.append(f"MLIR_OpHandle {fname}")
        fn = f"ASR_Create{op['name']}Op"
        lines.append(f"static inline MLIR_OpHandle {fn}(")
        lines.append("        " + ",\n        ".join(params) + ") {")
        n = len(stored)
        if n == 0:
            lines.append("    (void)ctx; (void)loc;")
            lines.append(f"    return ASR_DialectCreateOp(ctx, {op['kind']}, loc, NULL, 0);")
        else:
            lines.append(f"    ASR_DialectField fields[{n}];")
            for i, f in enumerate(stored):
                param = c_param_name(f.name or f.type)
                lines.extend(gen_field_assign(i, f, param))
            lines.append(f"    return ASR_DialectCreateOp(ctx, {op['kind']}, loc, fields, {n});")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def asr_member(field: asdl.Field) -> str:
    if field.name:
        return f"m_{field.name}"
    return field.type


def asr_count_member(field: asdl.Field) -> str:
    assert field.name
    return f"n_{field.name}"


def is_enum_field(asdl_type: str) -> bool:
    return asdl_type in SIMPLE_SUM_NAMES or asdl_type.endswith("Type")


def cpp_emit_field(field: asdl.Field) -> str:
    name = field.name
    asdl_type = field.type
    if name in SKIP_FIELDS:
        return ""
    fname = c_param_name(name or asdl_type)
    member = asr_member(field)
    if asdl_type == "expr":
        if field.seq:
            count = asr_count_member(field)
            return (f"        size_t n_{fname} = x.{count};\n"
                    f"        MLIR_OpHandle *{fname} = emit_expr_op_array(x.{member}, n_{fname});")
        if field.opt:
            return (f"        MLIR_ValueHandle {fname} = MLIR_INVALID_HANDLE;\n"
                    f"        if (x.{member}) {{ {fname} = emit_expr(*x.{member}); }}")
        return f"        MLIR_ValueHandle {fname} = emit_expr(*x.{member});"
    if asdl_type == "stmt":
        if field.seq:
            count = asr_count_member(field)
            return (f"        size_t n_{fname} = x.{count};\n"
                    f"        MLIR_OpHandle *{fname} = emit_stmt_op_array(x.{member}, n_{fname});")
        if field.opt:
            return (f"        MLIR_ValueHandle {fname} = MLIR_INVALID_HANDLE;\n"
                    f"        if (x.{member}) {{ {fname} = emit_stmt(*x.{member}); }}")
        return f"        MLIR_ValueHandle {fname} = emit_stmt(*x.{member});"
    if asdl_type == "symbol":
        if field.seq:
            return f"        string {fname} = emit_symbol_seq_ref(x.{member}, x.{asr_count_member(field)});"
        if field.opt:
            return (f"        string {fname} = str_lit(\"\");\n"
                    f"        if (x.{member}) {{ {fname} = emit_symbol_ref(*x.{member}); }}")
        return f"        string {fname} = emit_symbol_ref(*x.{member});"
    if asdl_type == "ttype":
        if field.seq:
            return f"        MLIR_TypeHandle {fname} = emit_type_seq_value(x.{member}, x.{asr_count_member(field)});"
        if field.opt:
            return (f"        MLIR_TypeHandle {fname} = MLIR_INVALID_HANDLE;\n"
                    f"        if (x.{member}) {{ {fname} = convert_type(*x.{member}); }}")
        return f"        MLIR_TypeHandle {fname} = convert_type(*x.{member});"
    if asdl_type == "identifier":
        if field.seq:
            return (f"        string {fname} = emit_identifier_seq("
                    f"x.{member}, x.{asr_count_member(field)});")
        return f"        string {fname} = asr_cstr(x.{member});"
    if asdl_type == "string":
        if field.opt:
            return (f"        string {fname} = str_lit(\"\");\n"
                    f"        if (x.{member}) {{ {fname} = asr_cstr(x.{member}); }}")
        return f"        string {fname} = asr_cstr(x.{member});"
    if asdl_type == "int":
        return f"        int64_t {fname} = x.{member};"
    if asdl_type == "bool":
        return f"        bool {fname} = x.{member};"
    if asdl_type == "float":
        return f"        double {fname} = x.{member};"
    if asdl_type == "void":
        return f"        int64_t {fname} = (int64_t)x.{member};"
    if is_enum_field(asdl_type):
        return f"        int64_t {fname} = (int64_t)x.{member};"
    if asdl_type == "array_index" and field.seq:
        count = asr_count_member(field)
        return (f"        size_t n_{fname} = x.{count};\n"
                f"        MLIR_OpHandle *{fname} = emit_array_index_op_array(x.{member}, n_{fname});")
    if field.seq and field_kind(asdl_type, True, field.opt) == "ASR_FIELD_OP_SEQ":
        count = asr_count_member(field)
        return (f"        size_t n_{fname} = x.{count};\n"
                f"        MLIR_OpHandle *{fname} = emit_product_op_array(x.{member}, n_{fname});")
    if field.seq:
        count = asr_count_member(field)
        return (f"        size_t n_{fname} = x.{count};\n"
                f"        MLIR_ValueHandle {fname} = MLIR_INVALID_HANDLE;\n"
                f"        (void)x.{member};")
    emit_fn = PRODUCT_EMIT_CPP.get(asdl_type)
    if emit_fn:
        if field.opt:
            return (f"        MLIR_ValueHandle {fname} = MLIR_INVALID_HANDLE;\n"
                    f"        if (x.{member}) {{ {fname} = {emit_fn}(*x.{member}); }}")
        return f"        MLIR_ValueHandle {fname} = {emit_fn}(x.{member});"
    if field.opt:
        return (f"        MLIR_ValueHandle {fname} = MLIR_INVALID_HANDLE;\n"
                f"        if (x.{member}) {{ {fname} = emit_product_value(x.{member}); }}")
    return f"        MLIR_ValueHandle {fname} = emit_product_value(x.{member});"


# Hand-written in asr_to_asr_dialect.cpp (module layout + multi-stmt do bodies).
