SKIP_VISITOR_OPS = {
    "Program", "TranslationUnit", "DoLoop", "Print", "FileWrite", "Variable",
    "StringFormat", "ArrayConstructor", "ArrayItem", "ArrayConstant",
}

# Embedded ASR products emitted by helpers in asr_to_asr_dialect.cpp.
PRODUCT_EMIT_CPP = {
    "do_loop_head": "emit_do_loop_head",
    "array_index": "emit_array_index",
}


def visitor_create_args(fields: list[asdl.Field]) -> list[str]:
    """Build ASR_Create*Op argument list matching generated API signatures."""
    args = []
    for f in fields:
        fname = c_param_name(f.name or f.type)
        fk = field_kind(f.type, f.seq, f.opt)
        # Product/node sequences use MLIR_OpHandle* + count in generated API.
        if f.seq and fk in (
            "ASR_FIELD_OP_SEQ",
            "ASR_FIELD_NODE_SEQ",
            "ASR_FIELD_EXPR_SEQ",
            "ASR_FIELD_STMT_SEQ",
        ):
            args.append(fname)
            args.append(f"n_{fname}")
            continue
        args.append(fname)
    return args


def gen_visitor_declarations(ops: list[dict]) -> str:
    lines = generated_file_lines()
    for op in ops:
        if op["category"] not in ("expr", "stmt"):
            continue
        if op["name"] in SKIP_VISITOR_OPS:
            continue
        lines.append(
            f"    void visit_{op['name']}(const ASR::{op['name']}_t &x);")
    if len(lines) == 2:
        lines.append("")
    return "\n".join(lines) + "\n"


def gen_visitor_implementations(ops: list[dict]) -> str:
    lines = generated_file_lines()
    for op in ops:
        if op["category"] not in ("expr", "stmt"):
            continue
        if op["name"] in SKIP_VISITOR_OPS:
            continue
        stored = [f for f in op["fields"] if f.name not in SKIP_FIELDS]
        lines.append(f"void ASRToAsrDialectVisitor::visit_{op['name']}(const ASR::{op['name']}_t &x) {{")
        for f in stored:
            code = cpp_emit_field(f)
            if code:
                # Drop class-body indent from helper snippets.
                lines.append(code[4:] if code.startswith("        ") else code)
        lines.append("    MLIR_LocationHandle op_loc = loc(x.base.base.loc);")
        fn = f"ASR_Create{op['name']}Op"
        create_args = visitor_create_args(stored)
        if stored:
            lines.append(
                f"    last_value = {fn}(&ctx, op_loc, {', '.join(create_args)});")
        else:
            lines.append(f"    last_value = {fn}(&ctx, op_loc);")
        if op["category"] == "stmt":
            lines.append("    append_current_stmt(last_value);")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def replace_marked_section(path: Path, start: str, end: str, content: str) -> None:
    text = path.read_text(encoding="utf-8")
    start_idx = text.find(start)
    end_idx = text.find(end)
    if start_idx < 0 or end_idx < 0 or end_idx < start_idx:
        raise RuntimeError(f"marker pair not found in {path}")
    end_idx += len(end)
    new_text = text[:start_idx] + start + "\n" + content + end + text[end_idx:]
    path.write_text(new_text, encoding="utf-8")


def check_marked_section(path: Path, start: str, end: str, expected: str) -> bool:
    if not path.exists():
        print(f"MISSING: {path}", file=sys.stderr)
        return False
    text = path.read_text(encoding="utf-8")
    start_idx = text.find(start)
    end_idx = text.find(end)
    if start_idx < 0 or end_idx < 0 or end_idx < start_idx:
        print(f"MARKERS MISSING: {path}", file=sys.stderr)
        return False
    start_idx += len(start)
    existing = text[start_idx:end_idx]
    if existing != "\n" + expected:
        print(f"STALE: {path} ({start})", file=sys.stderr)
        return False
    return True


def update_visitor_sources(codegen_dir: Path, ops: list[dict]) -> None:
    decls = gen_visitor_declarations(ops)
    impls = gen_visitor_implementations(ops)
    replace_marked_section(
        codegen_dir / "asr_to_asr_dialect.h",
        VISITOR_DECL_START, VISITOR_DECL_END, decls)
    replace_marked_section(
        codegen_dir / "asr_to_asr_dialect.cpp",
        VISITOR_IMPL_START, VISITOR_IMPL_END, impls)
    print(f"Updated {codegen_dir / 'asr_to_asr_dialect.h'}")
    print(f"Updated {codegen_dir / 'asr_to_asr_dialect.cpp'}")


def check_visitor_sources(codegen_dir: Path, ops: list[dict]) -> bool:
    decls = gen_visitor_declarations(ops)
    impls = gen_visitor_implementations(ops)
    ok = check_marked_section(
        codegen_dir / "asr_to_asr_dialect.h",
        VISITOR_DECL_START, VISITOR_DECL_END, decls)
    ok = check_marked_section(
        codegen_dir / "asr_to_asr_dialect.cpp",
        VISITOR_IMPL_START, VISITOR_IMPL_END, impls) and ok
    return ok


def gen_lowering_dispatch_h(ops: list[dict]) -> str:
    lines = generated_file_lines(
        "#pragma once",
        "",
        "#include \"asr_dialect_api.h\"",
        "",
        "/* Lowering handlers exist only for COMPILE_SUPPORTED_OPS (see asdl_to_asr_dialect.py). */",
        "",
    )
    for op in ops:
        if op["name"] in COMPILE_SUPPORTED_OPS:
            handler = f"ASR_Lower{op['name']}"
            lines.append(
                f"extern bool {handler}(ASR_LoweringContext *lc, MLIR_OpHandle op);")
    lines.extend([
        "",
        "static inline bool ASR_DialectLowerOneOp(",
        "        ASR_LoweringContext *ctx, MLIR_OpHandle op) {",
        "    ASR_DialectOpKind kind = ASR_DialectGetOpKind(op);",
        "    switch (kind) {",
    ])
    for op in ops:
        if op["name"] in COMPILE_SUPPORTED_OPS:
            handler = f"ASR_Lower{op['name']}"
            lines.append(f"    case {op['kind']}:")
            lines.append(f"        return {handler}(ctx, op);")
    lines.extend([
        "    default:",
        '        return ASR_LowerUnsupported(ctx, op, "ASR dialect op has no lowering yet");',
        "    }",
        "}",
        "",
    ])
    return "\n".join(lines)


def gen_enum_print_h(enums: dict[str, list[str]]) -> str:
    """C helpers: map semantic enum integers to keyword names for hybrid dump."""
    lines = generated_file_lines(
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "static inline const char *asr_enum_name_or_unknown(",
        "        const char *const *names, size_t n_names, int64_t v) {",
        "    if (v >= 0 && (size_t)v < n_names) {",
        "        return names[(size_t)v];",
        "    }",
        "    return NULL;",
        "}",
        "",
    )
    for enum_name, variants in sorted(enums.items()):
        c_names = f"ASR_ENUM_{enum_name.upper()}_NAMES"
        kw = [snake_case(v) for v in variants]
        lines.append(f"static const char *const {c_names}[] = {{")
        for k in kw:
            lines.append(f'    "{k}",')
        lines.append("};")
        lines.append(f"static const size_t {c_names}_COUNT = {len(kw)};")
        lines.append("")
        fn = f"asr_enum_{snake_case(enum_name)}_name"
        lines.append(f"static inline const char *{fn}(int64_t v) {{")
        lines.append(
            f"    return asr_enum_name_or_unknown({c_names}, {c_names}_COUNT, v);")
        lines.append("}")
        lines.append("")
    return "\n".join(lines) + "\n"


def collect_variable_enum_pp_fields(variable_op: dict | None) -> list[tuple[str, str]]:
    """(field name, ASDL enum type) for Variable I64 fields backed by simple sums."""
    if not variable_op:
        return []
    out: list[tuple[str, str]] = []
    for f in variable_op["fields"]:
        if not f.name or f.name in SKIP_FIELDS:
            continue
        if f.seq:
            continue
        if f.type in SIMPLE_SUM_NAMES:
            out.append((f.name, f.type))
    return sorted(out)


def gen_print_policy_h(ops: list[dict]) -> str:
    """Pretty-print elision and field-to-enum metadata for the hybrid ASR dump."""
    variable = next((o for o in ops if o["name"] == "Variable"), None)
    lines = generated_file_lines(
        "#pragma once",
        "",
        "#include \"generated/asr_dialect_schema.h\"",
        "#include \"generated/asr_dialect_enum_print.h\"",
        "#include \"asr_dialect_storage.h\"",
        "",
        "#include <string.h>",
        "",
        "typedef enum {",
        "    ASR_PP_ELIDE_NEVER = 0,",
        "    ASR_PP_ELIDE_ALWAYS,",
        "    ASR_PP_ELIDE_I64_ZERO,",
        "    ASR_PP_ELIDE_BOOL_FALSE,",
        "    ASR_PP_ELIDE_STR_EMPTY,",
        "} ASR_PpElideKind;",
        "",
        "typedef struct {",
        "    const char *field;",
        "    ASR_PpElideKind kind;",
        "} ASR_PpVariableElideRule;",
        "",
    )
    if variable:
        lines.append("static const ASR_PpVariableElideRule ASR_PP_VARIABLE_ELIDE[] = {")
        for f in variable["fields"]:
            fname = f.name or f.type
            rule = VARIABLE_FIELD_ELIDE.get(fname)
            if not rule:
                continue
            c_kind = PP_ELIDE_C_ENUM[rule]
            lines.append(f'    {{"{fname}", {c_kind}}},')
        lines.extend([
            "};",
            "static const size_t ASR_PP_VARIABLE_ELIDE_COUNT =",
            "    sizeof(ASR_PP_VARIABLE_ELIDE) / sizeof(ASR_PP_VARIABLE_ELIDE[0]);",
            "",
        ])
    else:
        lines.extend([
            "static const ASR_PpVariableElideRule ASR_PP_VARIABLE_ELIDE[] = {};",
            "static const size_t ASR_PP_VARIABLE_ELIDE_COUNT = 0;",
            "",
        ])

    enum_fields = collect_variable_enum_pp_fields(variable)
    lines.extend([
        "typedef const char *(*ASR_PpEnumNameFn)(int64_t);",
        "",
        "typedef struct {",
        "    const char *field;",
        "    const char *attr_category;",
        "    ASR_PpEnumNameFn name_fn;",
        "} ASR_PpEnumFieldDesc;",
        "",
        "static const ASR_PpEnumFieldDesc ASR_PP_ENUM_FIELDS[] = {",
    ])
    for fname, asdl_type in enum_fields:
        fn = f"asr_enum_{snake_case(asdl_type)}_name"
        cat = enum_pp_attr_category(asdl_type)
        lines.append(f'    {{"{fname}", "{cat}", {fn}}},')
    lines.extend([
        "};",
        "static const size_t ASR_PP_ENUM_FIELDS_COUNT =",
        "    sizeof(ASR_PP_ENUM_FIELDS) / sizeof(ASR_PP_ENUM_FIELDS[0]);",
        "",
        "static inline const ASR_PpEnumFieldDesc *asr_pp_lookup_enum_field(",
        "        const char *field) {",
        "    if (!field) {",
        "        return NULL;",
        "    }",
        "    for (size_t i = 0; i < ASR_PP_ENUM_FIELDS_COUNT; ++i) {",
        "        if (strcmp(field, ASR_PP_ENUM_FIELDS[i].field) == 0) {",
        "            return &ASR_PP_ENUM_FIELDS[i];",
        "        }",
        "    }",
        "    return NULL;",
        "}",
        "",
        "static inline bool asr_pp_apply_elide_rule(",
        "        ASR_PpElideKind kind, MLIR_OpHandle op, const char *field) {",
        "    switch (kind) {",
        "    case ASR_PP_ELIDE_ALWAYS:",
        "        return true;",
        "    case ASR_PP_ELIDE_I64_ZERO:",
        "        return asr_get_field_i64(op, field, 0) == 0;",
        "    case ASR_PP_ELIDE_BOOL_FALSE:",
        "        return !asr_get_field_bool(op, field, false);",
        "    case ASR_PP_ELIDE_STR_EMPTY:",
        "        return asr_get_field_str(op, field).size == 0;",
        "    default:",
        "        return false;",
        "    }",
        "}",
        "",
        "static inline bool asr_pp_variable_field_is_default(",
        "        const char *field, MLIR_OpHandle op) {",
        "    for (size_t i = 0; i < ASR_PP_VARIABLE_ELIDE_COUNT; ++i) {",
        "        if (strcmp(field, ASR_PP_VARIABLE_ELIDE[i].field) == 0) {",
        "            return asr_pp_apply_elide_rule(",
        "                ASR_PP_VARIABLE_ELIDE[i].kind, op, field);",
        "        }",
        "    }",
        "    return false;",
        "}",
        "",
        "static inline const char *asr_pp_enum_field_name(",
        "        const char *field, int64_t v) {",
        "    const ASR_PpEnumFieldDesc *desc = asr_pp_lookup_enum_field(field);",
        "    if (!desc || !desc->name_fn) {",
        "        return NULL;",
        "    }",
        "    return desc->name_fn(v);",
        "}",
        "",
        "static inline const char *asr_pp_enum_attr_category(const char *field) {",
        "    const ASR_PpEnumFieldDesc *desc = asr_pp_lookup_enum_field(field);",
        "    if (desc && desc->attr_category) {",
        "        return desc->attr_category;",
        "    }",
        "    return field;",
        "}",
        "",
    ])
    return "\n".join(lines)


def write_outputs(
    ops: list[dict],
    enums: dict[str, list[str]],
    out_mlir_dir: Path,
    out_codegen_dir: Path,
) -> None:
    out_mlir_dir.mkdir(parents=True, exist_ok=True)

    outputs = {
        out_mlir_dir / "asr_dialect_schema.h": gen_schema_h(ops),
        out_mlir_dir / "asr_dialect_api_generated.h": gen_api_generated_h(ops),
        out_mlir_dir / "asr_dialect_lowering_dispatch.h": gen_lowering_dispatch_h(ops),
        out_mlir_dir / "asr_dialect_enum_print.h": gen_enum_print_h(enums),
        out_mlir_dir / "asr_dialect_print_policy.h": gen_print_policy_h(ops),
    }
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path} ({len(content)} bytes)")
    update_visitor_sources(out_codegen_dir, ops)


def check_outputs(
    ops: list[dict],
    enums: dict[str, list[str]],
    out_mlir_dir: Path,
    out_codegen_dir: Path,
) -> bool:
    expected = {
        out_mlir_dir / "asr_dialect_schema.h": gen_schema_h(ops),
        out_mlir_dir / "asr_dialect_api_generated.h": gen_api_generated_h(ops),
        out_mlir_dir / "asr_dialect_lowering_dispatch.h": gen_lowering_dispatch_h(ops),
        out_mlir_dir / "asr_dialect_enum_print.h": gen_enum_print_h(enums),
        out_mlir_dir / "asr_dialect_print_policy.h": gen_print_policy_h(ops),
    }
    ok = True
    for path, content in expected.items():
        if not path.exists():
            print(f"MISSING: {path}", file=sys.stderr)
            ok = False
            continue
        existing = path.read_text(encoding="utf-8")
        if existing != content:
            print(f"STALE: {path}", file=sys.stderr)
            ok = False
    ok = check_visitor_sources(out_codegen_dir, ops) and ok
    return ok


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--asdl", type=Path, required=True)
    parser.add_argument("--out-mlir-dir", type=Path, required=True)
    parser.add_argument("--out-codegen-dir", type=Path, required=True,
                        help="libasr/codegen directory for visitor .h/.cpp")
    parser.add_argument("--check", action="store_true",
                        help="Verify committed generated files match ASR.asdl")
    args = parser.parse_args()

    mod = asdl.parse(str(args.asdl))
    ops = collect_ops(mod)
    enums = collect_simple_enums(mod)
    print(f"Generated {len(ops)} dialect ops")

    if args.check:
        return 0 if check_outputs(ops, enums, args.out_mlir_dir,
                                   args.out_codegen_dir) else 1

    write_outputs(ops, enums, args.out_mlir_dir, args.out_codegen_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main())
