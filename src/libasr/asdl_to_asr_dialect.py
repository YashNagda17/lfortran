SKIP_VISITOR_OPS = {
    "Program", "TranslationUnit", "DoLoop", "If", "WhileLoop", "Print",
    "FileWrite", "Variable", "Var", "StringFormat", "ArrayConstructor",
    "ArrayItem", "ArrayConstant",
}

