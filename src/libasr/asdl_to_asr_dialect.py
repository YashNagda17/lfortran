def field_id_enum(op_name: str, field_name: str) -> str:
    return f"ASR_DIALECT_FIELD_{op_name}_{field_name}"


def parse_storage_policy_overrides(policy_path: Path) -> dict[tuple[str, str], tuple[str, str, str]]:
    """Parse ASR_FIELD_STORAGE_OVERRIDES(X) entries from the policy header."""
    overrides: dict[tuple[str, str], tuple[str, str, str]] = {}
    if not policy_path.exists():
        return overrides
    text = policy_path.read_text(encoding="utf-8")
    for line in text.splitlines():
        line = line.strip()
        if not line.startswith("X("):
            continue
        if line.endswith("\\"):
            line = line[:-1].strip()
        if not line.endswith(")"):
            continue
        inner = line[2:-1]
        parts = [p.strip() for p in inner.split(",")]
        if len(parts) < 5:
            continue
        op_name, field_name, storage, region_kind, region_elem = parts[:5]
        overrides[(op_name, field_name)] = (storage, region_kind, region_elem)
    return overrides


def parse_region_layout(policy_path: Path) -> dict[tuple[str, str], int]:
    """Parse ASR_REGION_LAYOUT_LIST(X) entries from the policy header."""
    layouts: dict[tuple[str, str], int] = {}
    if not policy_path.exists():
        return layouts
    text = policy_path.read_text(encoding="utf-8")
    for line in text.splitlines():
        line = line.strip()
        if not line.startswith("X("):
            continue
        if line.endswith("\\"):
            line = line[:-1].strip()
        if not line.endswith(")"):
            continue
        inner = line[2:-1]
        parts = [p.strip() for p in inner.split(",")]
        if len(parts) != 3 or not parts[2].lstrip("-").isdigit():
            continue
        op_name, field_name, index_str = parts
        layouts[(op_name, field_name)] = int(index_str)
    return layouts


class FieldStoragePolicy:
    __slots__ = (
        "field_id", "storage", "region_kind", "region_element_kind",
        "operand_index", "region_index", "attr_index", "segment_attr",
    )

    def __init__(
        self,
        field_id: str,
        storage: str,
        region_kind: str = "ASR_DIALECT_REGION_NONE",
        region_element_kind: str = "ASR_DIALECT_REGION_ELEM_NONE",
        operand_index: int = -1,
        region_index: int = -1,
        attr_index: int = -1,
        segment_attr: str | None = None,
    ):
        self.field_id = field_id
        self.storage = storage
        self.region_kind = region_kind
        self.region_element_kind = region_element_kind
        self.operand_index = operand_index
        self.region_index = region_index
        self.attr_index = attr_index
        self.segment_attr = segment_attr


def default_field_storage(
        op_name: str, field_name: str, fk: str,
        category: str = "") -> FieldStoragePolicy:
    fid = field_id_enum(op_name, field_name)
    if fk in ATTR_FIELD_KINDS:
        return FieldStoragePolicy(fid, "ASR_STORAGE_ATTR")
    if fk == "ASR_FIELD_SYMBOL_REF":
        return FieldStoragePolicy(fid, "ASR_STORAGE_SYMBOL_REF_ATTR")
    if fk == "ASR_FIELD_SYMBOL_REF_SEQ":
        return FieldStoragePolicy(fid, "ASR_STORAGE_SYMBOL_REF_ARRAY_ATTR")
    if fk == "ASR_FIELD_TTYPE":
        return FieldStoragePolicy(fid, "ASR_STORAGE_RESULT_TYPE")
    if fk == "ASR_FIELD_TTYPE_OPT":
        return FieldStoragePolicy(fid, "ASR_STORAGE_TYPE_ATTR")
    if fk in EXPR_OPERAND_FIELD_KINDS:
        return FieldStoragePolicy(fid, "ASR_STORAGE_OPERAND")
    if fk in EXPR_OPT_OPERAND_FIELD_KINDS:
        if fk == "ASR_FIELD_STMT_OPT":
            return FieldStoragePolicy(
                fid, "ASR_STORAGE_OPTIONAL_REGION",
                "ASR_DIALECT_REGION_BODY", "ASR_DIALECT_REGION_ELEM_STMT")
        return FieldStoragePolicy(fid, "ASR_STORAGE_OPTIONAL_OPERAND")
    if fk in VARIADIC_OPERAND_FIELD_KINDS:
        elem = "ASR_DIALECT_REGION_ELEM_EXPR"
        if fk == "ASR_FIELD_OP_SEQ":
            elem = "ASR_DIALECT_REGION_ELEM_ANY"
        if fk == "ASR_FIELD_NODE_SEQ":
            elem = "ASR_DIALECT_REGION_ELEM_ANY"
        rk = "ASR_DIALECT_REGION_BODY"
        if field_name == "items":
            rk = "ASR_DIALECT_REGION_ITEMS"
        return FieldStoragePolicy(fid, "ASR_STORAGE_REGION", rk, elem)
    if fk in REGION_FIELD_KINDS or fk == "ASR_FIELD_NODE_SEQ":
        elem = "ASR_DIALECT_REGION_ELEM_STMT"
        if fk == "ASR_FIELD_NODE_SEQ":
            elem = "ASR_DIALECT_REGION_ELEM_ANY"
        rk = "ASR_DIALECT_REGION_BODY"
        if field_name == "orelse":
            rk = "ASR_DIALECT_REGION_ORELSE"
        if field_name == "items":
            rk = "ASR_DIALECT_REGION_ITEMS"
        return FieldStoragePolicy(fid, "ASR_STORAGE_REGION", rk, elem)
    if fk == "ASR_FIELD_SYMBOL":
        return FieldStoragePolicy(fid, "ASR_STORAGE_SYMBOL_REF_ATTR")
    if fk in ("ASR_FIELD_SYMBOL_REF_OPT", "ASR_FIELD_SYMBOL_REF_SEQ"):
        return FieldStoragePolicy(fid, "ASR_STORAGE_SYMBOL_REF_ATTR")
    if fk == "ASR_FIELD_TTYPE_SEQ":
        return FieldStoragePolicy(fid, "ASR_STORAGE_OMITTED")
    return FieldStoragePolicy(fid, "ASR_STORAGE_OMITTED")


def resolve_field_storage(
        op_name: str, field_name: str, fk: str,
        overrides: dict[tuple[str, str], tuple[str, str, str]],
        category: str = "") -> FieldStoragePolicy:
    key = (op_name, field_name)
    if key in overrides:
        storage, region_kind, region_elem = overrides[key]
        return FieldStoragePolicy(
            field_id_enum(op_name, field_name), storage, region_kind, region_elem)
    return default_field_storage(op_name, field_name, fk, category)


def assign_storage_indices(
        op_name: str,
        policies: list[tuple[str, FieldStoragePolicy]],
        region_layout: dict[tuple[str, str], int]) -> None:
    operand_idx = 0
    attr_idx = 0
    next_region = 0

    for fname, pol in policies:
        if pol.storage in ("ASR_STORAGE_ATTR", "ASR_STORAGE_SYMBOL_REF_ATTR",
                           "ASR_STORAGE_SYMBOL_REF_ARRAY_ATTR", "ASR_STORAGE_TYPE_ATTR"):
            pol.attr_index = attr_idx
            attr_idx += 1
        elif pol.storage in ("ASR_STORAGE_OPERAND", "ASR_STORAGE_OPTIONAL_OPERAND"):
            pol.operand_index = operand_idx
            operand_idx += 1
        elif pol.storage == "ASR_STORAGE_VARIADIC_OPERANDS":
            pol.operand_index = operand_idx
        elif pol.storage in ("ASR_STORAGE_REGION", "ASR_STORAGE_OPTIONAL_REGION"):
            key = (op_name, fname)
            if key in region_layout:
                pol.region_index = region_layout[key]
            else:
                pol.region_index = next_region
                next_region += 1


def compute_op_storage_policies(
        ops: list[dict],
        overrides: dict[tuple[str, str], tuple[str, str, str]],
        region_layout: dict[tuple[str, str], int]) -> dict[str, list[tuple[str, FieldStoragePolicy]]]:
    out: dict[str, list[tuple[str, FieldStoragePolicy]]] = {}
    for op in ops:
        stored = stored_dialect_fields(op)
        if not stored:
            continue
        policies: list[tuple[str, FieldStoragePolicy]] = []
        for f in stored:
            fname = f.name or f.type
            fk = field_kind(f.type, f.seq, f.opt)
            pol = resolve_field_storage(op["name"], fname, fk, overrides, op["category"])
            policies.append((fname, pol))
        for fname, storage, region_kind, region_elem in SYNTHETIC_SCOPE_FIELDS.get(
                op["name"], []):
            if any(n == fname for n, _ in policies):
                continue
            pol = FieldStoragePolicy(
                field_id_enum(op["name"], fname),
                storage, region_kind, region_elem)
            policies.append((fname, pol))
        assign_storage_indices(op["name"], policies, region_layout)
        out[op["kind"]] = policies
    return out


def dialect_layout_field_names() -> set[tuple[str, str]]:
    return {(op, field) for op, field, _note in DIALECT_LAYOUT_FIELDS}


def validate_policy_coverage(
        ops: list[dict],
        overrides: dict[tuple[str, str], tuple[str, str, str]],
        all_policies: dict[str, list[tuple[str, FieldStoragePolicy]]]) -> None:
    known: set[tuple[str, str]] = set()
    for op in ops:
        for f in stored_dialect_fields(op):
            known.add((op["name"], f.name or f.type))
        for fname, _storage, _rk, _re in SYNTHETIC_SCOPE_FIELDS.get(op["name"], []):
            known.add((op["name"], fname))
    for key in overrides:
        if key not in known:
            raise SystemExit(
                f"asdl_to_asr_dialect: unknown policy override {key[0]}.{key[1]}")
    for op in ops:
        stored = stored_dialect_fields(op)
        if not stored and op["name"] not in SYNTHETIC_SCOPE_FIELDS:
            continue
        policies = all_policies.get(op["kind"], [])
        if not policies:
            raise SystemExit(
                f"asdl_to_asr_dialect: missing storage policy for {op['name']}")
        pol_by_name = {n: p for n, p in policies}
        for f in stored:
            fname = f.name or f.type
            fk = field_kind(f.type, f.seq, f.opt)
            pres = "ASR_FIELD_OPTIONAL" if f.opt else "ASR_FIELD_REQUIRED"
            pol = pol_by_name.get(fname)
            if not pol:
                raise SystemExit(
                    f"asdl_to_asr_dialect: no policy for stored field "
                    f"{op['name']}.{fname}")
            if (pol.storage != "ASR_STORAGE_OMITTED" and
                    fk in PLACEHOLDER_EMITTER_FIELD_KINDS):
                raise SystemExit(
                    f"asdl_to_asr_dialect: field {op['name']}.{fname} "
                    f"uses placeholder emitter ({fk}) but storage is not OMITTED")


def gen_storage_merged_h(
        ops: list[dict],
        all_policies: dict[str, list[tuple[str, FieldStoragePolicy]]]) -> str:
    lines = generated_file_lines(
        "// Exhaustive merged storage policy (defaults + header overrides).",
        "// Regenerate with asdl_to_asr_dialect.py; do not edit.",
        "",
        "#pragma once",
        "",
        "#define ASR_FIELD_STORAGE_MERGED(X) \\",
    )
    entries: list[str] = []
    for op in ops:
        policies = all_policies.get(op["kind"], [])
        if not policies:
            continue
        for fname, pol in policies:
            entries.append(
                f"    X({op['name']}, {fname}, {pol.storage}, "
                f"{pol.region_kind}, {pol.region_element_kind}) \\")
    lines.extend(sorted(entries))
    lines.append("")
    return "\n".join(lines)


def gen_dialect_layout_h() -> str:
    lines = generated_file_lines(
        "#pragma once",
        "",
        "// Fields stored on dialect ops but not present in ASR.asdl.",
        "#define ASR_DIALECT_LAYOUT_FIELDS(X) \\",
    )
    for op_name, field_name, note in DIALECT_LAYOUT_FIELDS:
        lines.append(f"    /* {note} */ \\")
        lines.append(f"    X({op_name}, {field_name}) \\")
    lines.append("")
    return "\n".join(lines)


def schema_field_entries(op: dict, policies: list[tuple[str, FieldStoragePolicy]]) -> list[tuple]:
    """ASDL fields plus synthetic scope fields for schema/accessor emission."""
    stored = stored_dialect_fields(op)
    pol_by_name = {n: p for n, p in policies}
    entries: list[tuple] = []
    seen: set[str] = set()
    for f in stored:
        fname = f.name or f.type
        fk = field_kind(f.type, f.seq, f.opt)
        pres = "ASR_FIELD_OPTIONAL" if f.opt else "ASR_FIELD_REQUIRED"
        pol = pol_by_name.get(fname)
        if not pol:
            pol = default_field_storage(op["name"], fname, fk, op["category"])
        entries.append((fname, fk, pres, pol))
        seen.add(fname)
    for fname, _storage, _rk, _re in SYNTHETIC_SCOPE_FIELDS.get(op["name"], []):
        if fname in seen:
            continue
        pol = pol_by_name.get(fname)
        if not pol:
            continue
        entries.append((fname, "ASR_FIELD_OP", "ASR_FIELD_REQUIRED", pol))
    return entries


def op_region_count(_op_name: str, policies: list[tuple[str, FieldStoragePolicy]]) -> int:
    max_idx = -1
    for _fname, pol in policies:
        if pol.storage in ("ASR_STORAGE_REGION", "ASR_STORAGE_OPTIONAL_REGION"):
            max_idx = max(max_idx, pol.region_index)
    return max_idx + 1 if max_idx >= 0 else 0


def _gen_ids_lines(ops: list[dict], all_policies: dict) -> list[str]:
    """Field ID enum (body only, emitted inside asr_dialect_schema.h)."""
    lines = [
        "typedef enum {",
        "    ASR_DIALECT_FIELD_INVALID = 0,",
    ]
    field_ids: list[str] = []
    for op in ops:
        policies = all_policies.get(op["kind"], [])
        if policies:
            for fname, _fk, _pres, _pol in schema_field_entries(op, policies):
                field_ids.append(field_id_enum(op["name"], fname))
        else:
            for f in stored_dialect_fields(op):
                fname = f.name or f.type
                field_ids.append(field_id_enum(op["name"], fname))
    for fid in sorted(set(field_ids)):
        lines.append(f"    {fid},")
    lines.extend([
        "    ASR_DIALECT_FIELD_COUNT",
        "} ASR_DialectFieldId;",
        "",
    ])
    return lines


