def _gen_accessors_lines(ops: list[dict], all_policies: dict) -> list[str]:
    """Typed field getters (body only, emitted inside asr_dialect_api_generated.h)."""
    lines = [
        "static inline MLIR_OpHandle asr_operand_defining_op(MLIR_ValueHandle v) {",
        "    if (v == MLIR_INVALID_HANDLE) {",
        "        return MLIR_INVALID_HANDLE;",
        "    }",
        "    return MLIR_GetValueDefiningOp(v);",
        "}",
        "",
    ]

    for op in ops:
        op_name = op["name"]
        policies = all_policies.get(op["kind"], [])
        for fname, pol in policies:
            acc = c_accessor_name(op_name, fname)
            if pol.storage in ("ASR_STORAGE_OPERAND", "ASR_STORAGE_OPTIONAL_OPERAND"):
                lines.append(f"static inline MLIR_ValueHandle {acc}(MLIR_OpHandle op) {{")
                if pol.operand_index >= 0:
                    lines.append(
                        f"    if (MLIR_GetOpNumOperands(op) > (size_t){pol.operand_index}) {{")
                    lines.append(
                        f"        return MLIR_GetOpOperand(op, (size_t){pol.operand_index});")
                    lines.append("    }")
                lines.append("    return MLIR_INVALID_HANDLE;")
                lines.append("}")
                lines.append("")
                op_acc = f"{acc}Op"
                lines.append(f"static inline MLIR_OpHandle {op_acc}(MLIR_OpHandle op) {{")
                lines.append(f"    return asr_operand_defining_op({acc}(op));")
                lines.append("}")
                lines.append("")
            elif pol.storage == "ASR_STORAGE_SYMBOL_REF_ATTR":
                lines.append(f"static inline string {acc}(MLIR_OpHandle op) {{")
                lines.append(f"    return asr_get_field_str(op, \"{fname}\");")
                lines.append("}")
                lines.append("")
            elif pol.storage in ("ASR_STORAGE_REGION", "ASR_STORAGE_OPTIONAL_REGION"):
                title = fname[0].upper() + fname[1:]
                fn = f"ASR_{op_name}Get{title}Region"
                existing = [l.split("(")[0].split()[-1]
                            for l in lines if l.startswith("static inline MLIR_RegionHandle")]
                if fn not in existing:
                    lines.append(f"static inline MLIR_RegionHandle {fn}(MLIR_OpHandle op) {{")
                    if pol.region_index >= 0:
                        lines.append(
                            f"    if (MLIR_GetOpNumRegions(op) > (size_t){pol.region_index}) {{")
                        lines.append(
                            f"        return MLIR_GetOpRegion(op, (size_t){pol.region_index});")
                        lines.append("    }")
                    lines.append("    return MLIR_INVALID_HANDLE;")
                    lines.append("}")
                    lines.append("")

    return lines


def _gen_api_creators_lines(ops: list[dict]) -> list[str]:
    """ASR_Create*Op wrappers (body only, needs asr_dialect_api.h types)."""
    lines: list[str] = []
    for op in ops:
        stored = stored_dialect_fields(op)
        params = ["MLIR_Context *ctx", "MLIR_LocationHandle loc"]
        for f in stored:
            fname = c_param_name(f.name or f.type)
            if f.seq and f.type in ("expr", "stmt", "node"):
                params.append(f"MLIR_OpHandle *{fname}")
                params.append(f"size_t n_{fname}")
            elif f.type in ("expr", "stmt", "node"):
                params.append(f"MLIR_OpHandle {fname}")
            elif f.type == "symbol":
                params.append(f"ASR_SymbolRef {fname}")
            elif f.type == "ttype":
                params.append(f"MLIR_TypeHandle {fname}")
            elif f.type in ("identifier", "string"):
                params.append(f"string {fname}")
            elif f.type == "int" or is_enum_field(f.type):
                params.append(f"int64_t {fname}")
            elif f.type == "bool":
                params.append(f"bool {fname}")
            elif f.type == "float":
                params.append(f"double {fname}")
            elif f.seq:
                params.append(f"MLIR_OpHandle *{fname}")
                params.append(f"size_t n_{fname}")
            else:
                params.append(f"MLIR_OpHandle {fname}")
        fn = f"ASR_Create{op['name']}Op"
        lines.append(f"static inline MLIR_OpHandle {fn}(")
        lines.append("        " + ",\n        ".join(params) + ") {")
        n = len(stored)
        if n == 0:
            lines.append("    (void)ctx; (void)loc;")
            lines.append(
                f"    return ASR_DialectCreateOp(ctx, {op['kind']}, loc, NULL, 0);")
        else:
            lines.append(f"    ASR_DialectField fields[{n}] = {{}};")
            for i, f in enumerate(stored):
                param = c_param_name(f.name or f.type)
                lines.extend(gen_field_assign(i, f, param))
            lines.append(
                f"    return ASR_DialectCreateOp(ctx, {op['kind']}, loc, fields, {n});")
        lines.append("}")
        lines.append("")
    return lines


